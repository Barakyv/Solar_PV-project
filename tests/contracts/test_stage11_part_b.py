# ruff: noqa: E501  (assert messages and regular expressions; see test_stage11_part_a)
"""Stage 11, part B (docs/stage11_plan.md section 5, OP-67): the report sections, the traceability
table and the table of old against new results.

T-178 to T-184. The report is generated by `scripts/make_report_v7.py`; these tests check that every
number of the text is registered with a source file, that the files exist, that the old numbers are the
ones of `submission_evidence/`, and that the generator cannot score the test split.
"""

import re

import pandas as pd

from solarpv.config.paths import REPO_ROOT

DOCS = REPO_ROOT / "docs"
RUN = "outputs/runs/20261114T083930Z_final"
NUM = re.compile(r"\d[\d,]*(?:\.\d+)?")


def _report() -> str:
    return (DOCS / "report_v7.md").read_text(encoding="utf-8")


def _strip_ids(text: str) -> str:
    """Remove what is not a result: headings, identifiers (D-37, S11-05, F-30, D+1, C1), ISO dates,
    section references, file names with digits and code spans."""
    out = []
    for line in text.splitlines():
        if line.startswith("#"):
            continue
        out.append(line)
    t = "\n".join(out)
    t = re.sub(r"`[^`]*`", " ", t)  # code spans: tags, commands, file names
    t = re.sub(r"\d{4}-\d{2}(?:-\d{2})?(?:\.\.\d{4}-\d{2})?", " ", t)  # ISO dates and month spans
    t = re.sub(r"\b(?:stage|stages|phase|seed|step)s? \d+(?: and \d+)?", " ", t)  # names of steps and seeds
    t = re.sub(r"\b[A-Za-z]+[-+]?\d+(?:[a-z])?(?:[-–]\d+)?\b", " ", t)  # D-37, S11-05, F-30, D+1, C1, X100
    # section references, also lists of them ("sections 3.4 and 3.7", "Chapters 7 to 12"; part C)
    t = re.sub(r"\b(?:[Ss]ection|[Cc]hapter)s? \d+(?:\.\d+)?(?:(?:,| and| to)\s+\d+(?:\.\d+)?)*", " ", t)
    t = re.sub(r"\(\d+\.\d+\)", " ", t)
    return t


def test_t178_every_number_of_the_report_is_registered_with_a_source():
    trace = pd.read_csv(DOCS / "traceability.csv", dtype=str, keep_default_na=False)
    known = set()
    for v in trace["value_new"]:
        known.update(t.rstrip(",.") for t in NUM.findall(v))
    stray = sorted({t.rstrip(",.") for t in NUM.findall(_strip_ids(_report()))} - known)
    assert not stray, f"numbers of the report with no row in docs/traceability.csv: {stray}"
    assert list(trace.columns) == ["claim", "value_old", "value_new", "file", "script", "verified_on"]
    assert (trace["script"] == "scripts/make_report_v7.py").all() and (trace["file"] != "").all()


def test_t179_the_source_files_of_the_traceability_table_exist():
    trace = pd.read_csv(DOCS / "traceability.csv", dtype=str, keep_default_na=False)
    missing = set()
    for cell in trace["file"]:
        for part in re.split(r"[;,] ", cell):
            p = part.strip()
            if not any((REPO_ROOT / base / p).exists() for base in ("", RUN, f"{RUN}/evaluate/val",
                                                                    f"{RUN}/test", "outputs")):
                missing.add(p)
    assert not missing, f"files named in docs/traceability.csv do not exist: {sorted(missing)}"


def test_t180_the_old_numbers_are_those_of_the_submission_evidence():
    ovn = pd.read_csv(DOCS / "old_vs_new.csv", dtype=str, keep_default_na=False)
    old = pd.read_csv(REPO_ROOT / "submission_evidence/01_benchmark/benchmark_summary.csv")
    r = ovn[(ovn["section"] == "benchmark") & (ovn["item"] == "XGB-Opt indirect D+1")].iloc[0]
    x = old[(old["model"] == "xgb_sota") & (old["target"] == "indirect") & (old["horizon"] == 1)].iloc[0]
    assert r["old_value"] == f"{x['nRMSE_pct']:.2f} (n={int(x['n'])})"
    assert len(ovn[ovn["section"] == "benchmark"]) == 36  # six models, two targets, three horizons
    assert (ovn[["old_value", "new_test", "reason", "old_source", "new_source"]] != "").all().all()
    # the table in the errata is the generated table, with one row per line of the CSV
    er = (DOCS / "errata.md").read_text(encoding="utf-8")
    block = er.split("<!-- old-vs-new:begin")[1].split("<!-- old-vs-new:end -->")[0]
    assert sum(1 for ln in block.splitlines() if ln.startswith("| ")) == len(ovn) + 1  # + the header


def test_t181_the_report_keeps_the_rules_for_the_results():
    t = _report()
    for must in ("No model is declared the winner", "D-37", "tuning-split numbers", "operation-limited",
                 "the same hours for every model", "is not stated as a"):
        assert must in t, f"the report lacks: {must}"
    for banned in ("is the best model", "wins", "outperforms all", "physical effect of"):
        assert banned not in t, f"the report must not say: {banned}"
    # the quintile profile is not written as physics (M45) and the climatology margin is stated
    assert "binning" in t and "minimum detectable effect" in t
    # the five sections the stage owes (S-01, S-05, S-42 to S-44)
    for head in ("## 3.1 ", "## 3.5 ", "## 13. ", "## 14. ", "## 15. "):
        assert head in t


def test_t182_the_generator_only_reads_frozen_files():
    text = (REPO_ROOT / "scripts/make_report_v7.py").read_text(encoding="utf-8")
    for forbidden in ("allow_test=True", "--allow-test", "solarpv.pipeline", "run_step", "subprocess"):
        assert forbidden not in text, f"make_report_v7 must not use {forbidden}"
    assert "xgboost" not in text and "torch" not in text


def test_t183_the_rebuild_script_names_every_step_and_trains_nothing():
    text = (REPO_ROOT / "scripts/make_tables_from_frozen.py").read_text(encoding="utf-8")
    for step in ("solarpv.figures.analyses11", "make_report_v7.py", "solarpv.figures"):
        assert step in text
    for forbidden in ("--allow-test", "allow_test=True", "pipeline\", \"run", "--xgb-only", "--force"):
        assert forbidden not in text, forbidden


