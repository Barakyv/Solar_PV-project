# ruff: noqa: E501  (assert messages and regular expressions; see test_stage11_part_a)
"""Stage 11, part C (docs/stage11_plan.md section 6, OP-68): the final report v7 with its figures.

T-185 to T-189. The report and its README are generated by `scripts/make_report_v7.py`; these tests check that
every figure of the report is placed, numbered and referenced, that its caption is the current takeaway of its
builder, that the figures follow those of the submitted report, and that the README holds what the user asked for.
"""

import json
import re

import pandas as pd

from solarpv.config.paths import REPO_ROOT

DOCS = REPO_ROOT / "docs"


def _report() -> str:
    return (DOCS / "report_v7.md").read_text(encoding="utf-8")


def _figures() -> pd.DataFrame:
    return pd.read_csv(DOCS / "report_v7_figures.csv", dtype=str, keep_default_na=False)


def test_t185_every_figure_is_placed_numbered_and_referenced():
    t, f = _report(), _figures()
    placed = f[f["figure_id"] != ""]
    assert list(placed["number"].astype(int)) == list(range(1, len(placed) + 1))
    images = re.findall(r"^!\[([^\]]+)\]\(\.\./([^)]+)\)$", t, flags=re.M)
    assert [i for i, _ in images] == list(placed["figure_id"]), "images in the order of the table"
    for (fid, path), (_, row) in zip(images, placed.iterrows(), strict=True):
        assert (REPO_ROOT / path).exists(), path
        assert path == row["file"]
        n = row["number"]
        # one caption and at least one reference in the text
        assert len(re.findall(rf"\*\*Figure {n}\. ", t)) == 1, fid
        assert len(re.findall(rf"(?<!\*\*)Figure {n}\b(?!\.)", t)) >= 1, f"{fid} is not referenced in the text"


def test_t186_captions_are_the_current_takeaways_of_the_builders():
    t = _report()
    figs = json.loads((REPO_ROOT / "outputs/figures/figures_manifest.json").read_text(encoding="utf-8"))["figures"]
    for _, row in _figures().query("figure_id != ''").iterrows():
        spec = figs[row["figure_id"]]
        assert spec["kind"] == "process", "correction figures belong to the defense notes, not the report"
        caption = f"**Figure {row['number']}. {spec['title']}.** {spec['takeaway']}"
        assert caption in t, f"the caption of {row['figure_id']} is stale; run: python scripts/make_report_v7.py"


def test_t187_the_figures_follow_those_of_the_submitted_report():
    f = _figures()
    v6 = sorted(int(x) for x in f["v6_figure"] if x)
    assert v6 == list(range(1, 26)), "each of the 25 figures of v6 has one row"
    gone = f[f["figure_id"] == ""]
    assert (gone["relation"].str.startswith("not redrawn: ")).all() and len(gone) == 6
    assert set(gone["v6_figure"]) == {"14", "19", "20", "21", "23", "25"}
    assert not re.search(r"!\[C-\d+\]", _report()), "no correction figure in the report"


def test_t189_the_text_and_the_figure_give_the_same_shares_of_bias_and_seed_variance():
    """X115: section 12.3 uses the aggregation of S11-11 (mean over the cells, then the maximum over the models)."""
    figs = json.loads((REPO_ROOT / "outputs/figures/figures_manifest.json").read_text(encoding="utf-8"))["figures"]
    facts = figs["S11-11"]["facts"]
    tr = pd.read_csv(DOCS / "traceability.csv", dtype=str, keep_default_na=False).set_index("claim")
    assert tr.loc["bias2 share max, validation, %", "value_new"] == f"{100 * facts['b2_max']:.1f}"
    assert tr.loc["bias2 share max, test, %", "value_new"] == f"{100 * facts['b2_test_max']:.1f}"
    assert tr.loc["seed variance share max, %", "value_new"] == f"{100 * facts['sv_max']:.1f}"


def test_t188_the_readme_holds_the_note_the_availability_the_appendices_and_the_open_decisions():
    r = (DOCS / "report_v7_README.md").read_text(encoding="utf-8")
    for must in ("## Correction note (D-02)", "## Data and code availability (S-45", "docs/errata.md",
                 "docs/traceability.csv", "docs/data_processing_record.md", "## Decisions still open",
                 "Q-09", "is not decided here"):
        assert must in r, must
    t = _report()
    assert "## 16. Data and Code Availability" in t and "## 17. References" in t
    assert "Q-09" not in t, "the open decision Q-09 is listed in the README, not in the report"
    # no coordinates in the report (T-45): no decimal degrees of the form 29.xxxx or 35.xxxx
    assert not re.search(r"\b(?:29|30|34|35)\.\d{3,}\b", t)
