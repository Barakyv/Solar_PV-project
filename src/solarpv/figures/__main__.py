"""The figure book (docs/figures_plan.md).

    python -m solarpv.figures build [--stage 6] [--only S06-02,S06-03]
    python -m solarpv.figures list
    python -m solarpv.figures catalog      # rewrite the catalog and the gallery from the manifest

Outputs: outputs/figures/<stage>/<ID>_<slug>.png, outputs/figures/figures_manifest.json,
outputs/figures/gallery.html and docs/figure_catalog.md.
"""

import argparse
import html
import json
import string
import time
from pathlib import Path

import matplotlib.pyplot as plt

from solarpv.config.paths import DOCS_DIR, OUTPUTS_DIR, REPO_ROOT
from solarpv.config.provenance import git_commit, sha256, text_sha256
from solarpv.figures.registry import EXISTING, STAGE_NAMES, STAGES, load_all
from solarpv.figures.style import DPI, RC

FIG_DIR = OUTPUTS_DIR / "figures"
MANIFEST = FIG_DIR / "figures_manifest.json"
CATALOG = DOCS_DIR / "figure_catalog.md"
GALLERY = FIG_DIR / "gallery.html"
TEXT_SUFFIXES = {".csv", ".json", ".yaml", ".yml", ".md", ".txt", ".py"}


def input_hash(rel: str) -> str:
    path = REPO_ROOT / rel
    return text_sha256(path) if path.suffix.lower() in TEXT_SUFFIXES else sha256(path)


def render_takeaway(template: str, facts: dict) -> str:
    names = {f[1].split(".")[0].split("[")[0].split("!")[0].split(":")[0]
             for f in string.Formatter().parse(template) if f[1]}
    missing = sorted(names - set(facts))
    assert not missing, f"takeaway needs facts {missing}"
    return template.format(**facts)


def load_manifest() -> dict:
    if MANIFEST.exists():
        return json.loads(MANIFEST.read_text(encoding="utf-8"))
    return {"stage": "figures", "figures": {}}


def build(only=None, stage=None) -> dict:
    specs = [s for s in load_all()
             if (not only or s.id in only) and (not stage or s.stage == stage)]
    assert specs, "no figure selected"
    manifest = load_manifest()
    commit = git_commit()
    for spec in specs:
        t = time.time()
        with plt.rc_context(RC):
            fig, facts = spec.build()
            out = FIG_DIR / spec.stage_dir / spec.filename
            out.parent.mkdir(parents=True, exist_ok=True)
            fig.savefig(out, dpi=DPI, metadata={"Software": None})
            plt.close(fig)
        facts = json.loads(json.dumps(facts, default=float))
        manifest["figures"][spec.id] = {
            "stage": spec.stage, "kind": spec.kind, "title": spec.title,
            "file": out.relative_to(REPO_ROOT).as_posix(), "file_sha256": sha256(out),
            "inputs": {rel: input_hash(rel) for rel in spec.inputs},
            "facts": facts, "takeaway": render_takeaway(spec.takeaway, facts),
            "git_commit": commit,
        }
        print(f"{spec.id:7s} {time.time() - t:5.1f} s  {out.relative_to(REPO_ROOT).as_posix()}")
    order = [s.id for s in load_all()]
    manifest["figures"] = {k: manifest["figures"][k] for k in order if k in manifest["figures"]}
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(manifest, indent=1, ensure_ascii=False) + "\n",
                        encoding="utf-8", newline="\n")
    write_catalog(manifest)
    return manifest


def existing_figures(stage: str) -> list[tuple[str, str]]:
    rows = []
    for st, folder, producer, pattern in EXISTING:
        if st == stage:
            for p in sorted((REPO_ROOT / folder).glob(pattern)):
                rows.append((p.relative_to(REPO_ROOT).as_posix(), producer))
    return rows


def catalog_text(manifest: dict) -> str:
    specs = load_all()
    lines = ["# Figure catalog", "",
             "Generated by `python -m solarpv.figures catalog` from `outputs/figures/"
             "figures_manifest.json`; do not edit by hand. Plan and rules: "
             "`docs/figures_plan.md`. Every takeaway is formatted from the facts the figure's "
             "builder computed. Process figures show the method; correction figures belong to "
             "`docs/defense_notes.md`.", "",
             f"Figures registered: {len(specs)} "
             f"({sum(s.kind == 'process' for s in specs)} process, "
             f"{sum(s.kind == 'correction' for s in specs)} correction). "
             f"Gallery for choosing: `{GALLERY.relative_to(REPO_ROOT).as_posix()}`.", ""]
    for stage in STAGES:
        here = [s for s in specs if s.stage == stage]
        old = existing_figures(stage)
        if not here and not old:
            continue
        title = (STAGE_NAMES[stage] if stage == "correction"
                 else f"Stage {stage}: {STAGE_NAMES[stage]}")
        lines += [f"## {title}", ""]
        for s in here:
            entry = manifest["figures"].get(s.id)
            lines += [f"### {s.id}. {s.title}", "",
                      f"- **Question:** {s.question}",
                      f"- **Shows:** {s.description}",
                      f"- **Takeaway:** {entry['takeaway'] if entry else '(not built yet)'}",
                      f"- **Led to:** {s.led_to}",
                      f"- **File:** `{entry['file'] if entry else s.stage_dir + '/' + s.filename}`",
                      ""]
        if old:
            lines += ["Figures made earlier by the stage's own producer:", ""]
            lines += [f"- `{path}` ({producer})" for path, producer in old]
            lines += [""]
    return "\n".join(lines).rstrip() + "\n"


def gallery_text(manifest: dict) -> str:
    cards = []
    for s in load_all():
        e = manifest["figures"].get(s.id)
        if not e:
            continue
        rel = Path(e["file"]).relative_to("outputs/figures").as_posix()
        cards.append(
            f'<figure class="{s.kind}"><label><input type="checkbox" value="{s.id}"> '
            f'<b>{s.id}</b> {html.escape(s.title)}</label><a href="{rel}"><img src="{rel}" '
            f'alt="{html.escape(s.description)}" loading="lazy"></a><figcaption>'
            f'{html.escape(e["takeaway"])}<br><i>Led to:</i> {html.escape(s.led_to)}'
            f'</figcaption></figure>')
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>Figure book"
            "</title><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">"
            "<style>body{font:14px system-ui,sans-serif;margin:16px;background:#fff;color:#111}"
            "main{display:grid;grid-template-columns:repeat(auto-fill,minmax(420px,1fr));gap:16px}"
            "figure{margin:0;border:1px solid #ddd;border-radius:8px;padding:10px}"
            "figure.correction{border-color:#D55E00}img{width:100%;height:auto}"
            "figcaption{font-size:12px;color:#444;margin-top:6px}#sel{position:sticky;top:0;"
            "background:#fff;padding:8px 0}</style></head><body><h1>Figure book</h1>"
            "<div id=\"sel\">Selected: <span id=\"ids\"></span> <button onclick=\"navigator."
            "clipboard.writeText(document.getElementById('ids').textContent)\">Copy IDs</button>"
            "</div><main>" + "".join(cards) + "</main><script>const b=[...document.querySelectorAll"
            "('input')];function u(){document.getElementById('ids').textContent=b.filter(x=>"
            "x.checked).map(x=>x.value).join(', ')}b.forEach(x=>x.onchange=u)</script>"
            "</body></html>\n")


def write_catalog(manifest: dict | None = None) -> None:
    manifest = manifest or load_manifest()
    CATALOG.write_text(catalog_text(manifest), encoding="utf-8", newline="\n")
    GALLERY.write_text(gallery_text(manifest), encoding="utf-8", newline="\n")


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m solarpv.figures")
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build")
    b.add_argument("--stage")
    b.add_argument("--only", help="comma-separated figure ids")
    sub.add_parser("list")
    sub.add_parser("catalog")
    a = ap.parse_args(argv)
    if a.cmd == "build":
        build(only=set(a.only.split(",")) if a.only else None, stage=a.stage)
    elif a.cmd == "list":
        for s in load_all():
            print(f"{s.id:7s} {s.stage:10s} {s.kind:10s} {s.title}")
    else:
        write_catalog()


if __name__ == "__main__":
    main()
