"""Stage 11, part B: the figures of the report sections, the traceability and the old against new
results (docs/stage11_plan.md section 5, OP-67). S11-18 and S11-19 are process figures; C-11 and C-12
are correction figures for docs/defense_notes.md.

Every number in a takeaway is computed by the builder from the files of the final run, the tables of
`outputs/11_analyses/`, `docs/traceability.csv` and `docs/old_vs_new.csv` (both generated by
`scripts/make_report_v7.py`); each claim is asserted here.
"""

import numpy as np
import pandas as pd

from solarpv.figures import _data as D
from solarpv.figures.registry import register
from solarpv.figures.s10_final import FINAL
from solarpv.figures.style import C, arrow, blank, box, subplots

TRACE = "docs/traceability.csv"
OVN = "docs/old_vs_new.csv"
A = "outputs/11_analyses"
M6 = ["xgb_sota", "lstm_sota", "tft_96", "tft_168", "tft", "patchtst"]
FIXED_DOCS = ("Solar_PV_Forecasting_Report_CORRECTED_v6.docx", "PROJECT_MASTER.md")


def _first(path: str) -> str:
    return path.split(";")[0].split(", ")[0].strip()


def _family(row) -> str:
    f = _first(row["file"])
    if any(d in f for d in FIXED_DOCS):
        return "quoted from a fixed document"
    if "11_analyses" in f:
        return "tables of the analyses (part A)"
    if "runs/" in f:
        return "tables and explanations of the final run"
    if f.startswith(("outputs/", "configs/", "src/", "submission_evidence")):
        return "data stages, constants and the old evidence"
    return "tables and explanations of the final run"  # paths relative to the run folder


# ── S11-18: where each number of the report comes from ──────────────────────

@register(
    "S11-18", "11", "number_sources", "Where every number of the report comes from",
    "Does every number of the report have a source file and a script, and how are the numbers "
    "spread over the sources?",
    "Left: the registered numbers of the report by kind of source. Right: the twelve files that "
    "supply the most numbers. The registry is written by the script that writes the text, so a number "
    "cannot reach the report without a row.",
    "The {n_rows} registered numbers of the report are read from {n_files} files: {n_run} from the "
    "tables and explanations of the final run, {n_ana} from the tables of the analyses of part A, "
    "{n_data} from the data stages and constants, and {n_quoted} are quotations of the submitted "
    "report or of the project documents. Every row names the script that formats it; a test fails "
    "when a number of the text has no row.",
    "docs/traceability.csv and the table of old against new results (S-01, S-05, S-42 to S-44).",
    (TRACE,))
def s11_number_sources():
    t = D.csv(TRACE, dtype=str, keep_default_na=False)
    assert list(t.columns) == ["claim", "value_old", "value_new", "file", "script", "verified_on"]
    assert (t["script"] == "scripts/make_report_v7.py").all() and (t["file"] != "").all()
    t["family"] = t.apply(_family, axis=1)
    fam = t["family"].value_counts()
    files = t["file"].map(_first)
    top = files.value_counts().head(12)
    order = ["tables and explanations of the final run", "tables of the analyses (part A)",
             "data stages, constants and the old evidence", "quoted from a fixed document"]
    colours = [C["blue"], C["orange"], C["green"], C["grey"]]
    fig, (ax, ax2) = subplots(1, 2, width=9.0, height=3.9, gridspec_kw={"width_ratios": [1, 1.35]})
    ax.barh(range(len(order)), [int(fam.get(k, 0)) for k in order], color=colours)
    ax.set_yticks(range(len(order)), [k.replace(" and ", " and\n", 1) for k in order], fontsize=7)
    ax.invert_yaxis()
    ax.set_xlabel("registered numbers")
    for i, k in enumerate(order):
        ax.text(int(fam.get(k, 0)) + 0.5, i, str(int(fam.get(k, 0))), va="center", fontsize=7)
    ax2.barh(range(len(top)), top.to_numpy(), color=C["sky"])
    ax2.set_yticks(range(len(top)), [p.split("/")[-1] if len(p) > 44 else p for p in top.index],
                   fontsize=6.2)
    ax2.invert_yaxis()
    ax2.set_xlabel("registered numbers")
    return fig, {"n_rows": len(t), "n_files": int(files.nunique()),
                 "n_run": int(fam.get(order[0], 0)), "n_ana": int(fam.get(order[1], 0)),
                 "n_data": int(fam.get(order[2], 0)), "n_quoted": int(fam.get(order[3], 0))}


# ── S11-19: the rebuild from the frozen predictions ─────────────────────────

@register(
    "S11-19", "11", "rebuild_chain", "The rebuild from the frozen predictions",
    "What does the stage-11 rebuild read, what does it write, and what does it never run?",
    "The four steps of `scripts/make_tables_from_frozen.py` with what each reads and writes, and, "
    "below, what the chain never does. The counts are read from the files the steps wrote.",
    "The chain starts from the {n_steps} steps of the final run that are `ok` and writes "
    "{n_tables} tables of analyses, the figures of stage 11, {n_rows} registered numbers and "
    "{n_ovn} rows of old against new results. It never runs the step `test` (the test split was "
    "scored once, {n_test_scored} time in the access log), never trains a model and never changes "
    "a budget, a seed or a rule (D-37).",
    "S-45 (Q-30, option a): the counterpart of `--skip-train`; `--xgb-only`, a training run, is left "
    "for the end of the stage.",
    (f"{FINAL}/run.json", f"{A}/manifest.json", TRACE, OVN,
     "outputs/07_evaluation/test_access_log.csv"))
def s11_rebuild_chain():
    steps = pd.DataFrame([{"step": k, "status": v["status"]}
                          for k, v in D.jload(f"{FINAL}/run.json")["steps"].items()])
    assert (steps["status"] == "ok").all()
    man = D.jload(f"{A}/manifest.json")
    n_tables = len(man["rows"])
    log = D.csv("outputs/07_evaluation/test_access_log.csv")
    n_scored = int(log["command"].str.contains("step test: score the test split", regex=False).sum())
    assert n_scored == 1
    tr = D.csv(TRACE, dtype=str, keep_default_na=False)
    ov = D.csv(OVN, dtype=str, keep_default_na=False)
    fig, ax = subplots(width=9.0, height=3.5)
    blank(ax)
    xs = [0.01, 0.265, 0.52, 0.775]
    texts = [
        f"1. status of the run\n{len(steps)} steps ok,\noutputs as recorded",
        f"2. analyses11\n{n_tables} tables\n(saved forecasts,\nstage-6 truth)",
        "3. figures\nstage 11\n(tables and\nreport files)",
        f"4. make_report_v7\n{len(tr)} numbers,\n{len(ov)} old-vs-new rows,\nerrata table"]
    for x, text in zip(xs, texts, strict=True):
        box(ax, x, 0.5, 0.215, 0.38, text, face=C["light"], size=8.4)
    for x in xs[:-1]:
        arrow(ax, x + 0.218, 0.69, x + 0.252, 0.69)
    box(ax, 0.01, 0.08, 0.98, 0.26,
        "never run by the chain:\nthe step test (the test split is scored once, D-32), the training of any model,\n"
        "--allow-test, a change of a budget, a seed or a rule (D-37)",
        face="white", edge=C["red"], size=8.4, color=C["red"])
    return fig, {"n_steps": len(steps), "n_tables": n_tables, "n_rows": len(tr),
                 "n_ovn": len(ov), "n_test_scored": n_scored}


# ── C-11: the eight conclusions of the submitted report ─────────────────────

def _route_pairs(rel: str) -> pd.Series:
    r = D.csv(rel)
    r = r[r["model"].isin(M6)].groupby(["model", "horizon", "route"])["nRMSE_pct"].mean().unstack("route")
    return r["direct"] - r["indirect_to_power"]


@register(
    "C-11", "correction", "conclusions_ledger", "The eight conclusions of the submitted report, one by one",
    "Which conclusions of the submitted report does the rebuilt pipeline reproduce?",
    "One row per conclusion C1 to C8 of the submitted report, with the rebuilt evidence and a verdict. "
    "Green: reproduced; orange: replaced by a different statement; red: not supported.",
    "Of the eight conclusions, {n_ok} is reproduced, {n_replaced} are replaced by a different "
    "statement and {n_bad} are not supported. The route (C2) is nominally the other way in "
    "{route_val} of 18 pairs on validation and {route_test} of 18 on test; the encoder (C5) has "
    "{enc_sig} of 12 cells significant; PatchTST (C4) is {pt_lo:.2f} to {pt_hi:.2f} pp behind XGB "
    "in kW (the submitted report stated {v6_gap:.1f} pp, in the units of the target, F-06); the "
    "climatology margin (C7) is significant in {clim_sig} cell of 6.",
    "docs/defense_notes.md section 16; docs/report_v7.md section 14.",
    (f"{A}/patchtst_gap.csv", f"{A}/encoder_length.csv", f"{A}/horizon_robustness.csv",
     f"{A}/quintile_control.csv", f"{FINAL}/evaluate/val/route_comparison.csv",
     f"{FINAL}/test/test/route_comparison.csv", f"{FINAL}/report/report_dm_kw_test.csv",
     f"{FINAL}/report/report_benchmark_test.csv", f"{FINAL}/report/report_benchmark_val.csv",
     f"{FINAL}/explain/xgb/xgb_shap_groups.csv", f"{FINAL}/explain/tft/tft_attention_summary.csv",
     OVN), kind="correction")
def c11_conclusions():
    rv, rt = _route_pairs(f"{FINAL}/evaluate/val/route_comparison.csv"), \
        _route_pairs(f"{FINAL}/test/test/route_comparison.csv")
    route_val, route_test = int((rv < 0).sum()), int((rt < 0).sum())
    assert (route_val, route_test) == (16, 11)
    enc = D.csv(f"{A}/encoder_length.csv")
    enc_sig = int(enc["significant"].sum())
    assert enc_sig == 1 and not enc[enc["split"] == "val"]["significant"].any()
    pt = D.csv(f"{A}/patchtst_gap.csv")
    px = pt[pt["model_b"] == "xgb_sota"]
    assert px["significant"].all()
    old = D.csv(OVN, dtype=str, keep_default_na=False)
    o = old[(old["section"] == "benchmark") & (old["item"].isin(["PatchTST indirect D+1", "XGB-Opt indirect D+1"]))]
    v6 = {r["item"]: float(r["old_value"].split()[0]) for _, r in o.iterrows()}
    v6_gap = v6["PatchTST indirect D+1"] - v6["XGB-Opt indirect D+1"]
    assert px["diff_a_minus_b_pp"].min() > v6_gap
    hz = D.csv(f"{A}/horizon_robustness.csv")
    hz = hz[hz["model"].isin(M6)]
    assert (hz[hz["split"] == "val"]["D3_minus_D1_pp"] < 0).sum() > 6 > 0
    assert (hz[hz["split"] == "test"]["D3_minus_D1_pp"] > 0).all()
    dm = D.csv(f"{FINAL}/report/report_dm_kw_test.csv")
    clim = dm[(dm["model_a"] == "climatology") & (dm["model_b"] == "xgb_sota")]
    clim_sig = int(clim["significant"].sum())
    assert clim_sig == 1 and len(clim) == 6
    qc = D.csv(f"{A}/quintile_control.csv")
    q = qc[(qc["target"] == "direct") & (qc["horizon"] == 1) & (qc["split"] == "test")].set_index("bin")
    assert q.loc[1, "me_calibrated_kw"] > 0 > q.loc[5, "me_calibrated_kw"]
    rows = [
        ("C1", "XGB-Opt first, overlapping with TFT-96", "no model is declared the best (D-37)", "orange"),
        ("C2", "indirect route better by about 2 pp", f"direct nominally better in {route_val} of 18 "
         f"(validation), {route_test} of 18 (test)", "red"),
        ("C3", "flat horizon profile of XGB-Opt", "the sign of D+3 minus D+1 reverses between periods", "orange"),
        ("C4", "PatchTST within 1.2 pp of XGB-Opt", f"{px['diff_a_minus_b_pp'].min():.2f} to "
         f"{px['diff_a_minus_b_pp'].max():.2f} pp behind, 12 of 12 significant", "red"),
        ("C5", "96-hour encoder consistently better", f"{enc_sig} of 12 cells significant; sign depends "
         "on the route", "red"),
        ("C6", "SHAP and attention agree on -24, -48, -168 h", "GFS group leads; attention is a daily "
         "pattern", "red"),
        ("C7", "differences below the detectable effect", f"climatology separated in {clim_sig} of 6 cells "
         "(test)", "green"),
        ("C8", "error peaks in the second production quintile", "the profile appears for an unbiased "
         "control forecast", "red")]
    colour = {"green": "#CFEFE4", "orange": "#FBE3B3", "red": "#F6C9B5"}
    fig, ax = subplots(width=9.6, height=3.9)
    ax.set_axis_off()
    t = ax.table(cellText=[[a, b, c] for a, b, c, _ in rows],
                 colLabels=["", "submitted report", "rebuilt evidence"], loc="center",
                 cellLoc="left", colWidths=[0.05, 0.38, 0.52])
    t.auto_set_font_size(False)
    t.set_fontsize(7.2)
    t.scale(1, 1.75)
    for (r, _), cell in t.get_celld().items():
        cell.set_edgecolor("0.8")
        if r == 0:
            cell.set_facecolor(C["light"])
        else:
            cell.set_facecolor(colour[rows[r - 1][3]])
    counts = pd.Series([r[3] for r in rows]).value_counts()
    return fig, {"n_ok": int(counts.get("green", 0)), "n_replaced": int(counts.get("orange", 0)),
                 "n_bad": int(counts.get("red", 0)), "route_val": route_val, "route_test": route_test,
                 "enc_sig": enc_sig, "pt_lo": float(px["diff_a_minus_b_pp"].min()),
                 "pt_hi": float(px["diff_a_minus_b_pp"].max()), "v6_gap": float(v6_gap),
                 "clim_sig": clim_sig}


# ── C-12: the route advantage, old against new ──────────────────────────────

@register(
    "C-12", "correction", "route_old_new", "The route advantage: submitted report and rebuild",
    "Is the indirect route better than the direct route by about two points, as the submitted report "
    "stated?",
    "For XGB-Opt and BiLSTM-Opt at each horizon: the nRMSE of the direct route minus that of the "
    "indirect route, in kW, as submitted (bars on the left of each group) and in the rebuild on "
    "validation and on test (seed mean). Positive: the indirect route is better.",
    "The submitted report found the indirect route better by {old_lo:.2f} to {old_hi:.2f} pp. In "
    "the rebuild the difference is {val_lo:+.2f} to {val_hi:+.2f} pp on validation and "
    "{test_lo:+.2f} to {test_hi:+.2f} pp on test, with the sign of {changed} of the 6 bars changing "
    "between the two periods: the advantage is not reproduced, and neither route is declared better.",
    "docs/defense_notes.md section 16; docs/report_v7.md section 13.2 (C-16, C-34).",
    (OVN,), kind="correction")
def c12_route_old_new():
    ov = D.csv(OVN, dtype=str, keep_default_na=False)
    r = ov[ov["section"] == "route"].copy()
    assert len(r) == 6
    for col in ("old_value", "new_validation", "new_test"):
        r[col] = r[col].astype(float)
    old_lo, old_hi = r["old_value"].min(), r["old_value"].max()
    assert old_lo > 1.5 and old_hi < 2.2  # the 1.66 to 2.10 of v6
    changed = int(((r["new_validation"] < 0) != (r["new_test"] < 0)).sum())
    fig, ax = subplots(width=7.4, height=3.3)
    x = np.arange(len(r))
    w = 0.27
    ax.bar(x - w, r["old_value"], w, color=C["grey"], label="submitted report")
    ax.bar(x, r["new_validation"], w, color=C["blue"], label="rebuild, validation")
    ax.bar(x + w, r["new_test"], w, color=C["orange"], label="rebuild, test")
    ax.axhline(0, color="black", lw=0.7)
    ax.set_xticks(x, [i.replace(", direct minus indirect", "") for i in r["item"]], fontsize=7)
    ax.set_ylabel("direct minus indirect, pp (kW)")
    ax.set_ylim(top=float(r["old_value"].max()) + 0.7)
    ax.legend(fontsize=7, ncol=3, loc="upper center")
    return fig, {"old_lo": float(old_lo), "old_hi": float(old_hi),
                 "val_lo": float(r["new_validation"].min()), "val_hi": float(r["new_validation"].max()),
                 "test_lo": float(r["new_test"].min()), "test_hi": float(r["new_test"].max()),
                 "changed": changed}
