"""Build docs/data_record_numbers.md: every number of the data-processing record, read from the
stage manifests and audit outputs (never typed by hand).

    python scripts/build_data_record.py

tests/contracts/test_data_record.py fails when the file is out of date, so a rerun of a stage
that changes a number cannot go unnoticed.
"""

